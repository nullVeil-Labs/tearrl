"""
Scripted policies, mixtures and calibration anchors (build-order step 3, B.3).

The anchors matter as much as the environment: every blind threshold in
App. D is defined against these policies, so an anchor that fails to saturate
its channel silently moves a gate in H1.
"""

from __future__ import annotations

import random

import pytest

from tearrl import TearWorld, Verb
from tearrl.policies import (
    ALL_POLICIES,
    ALWAYS_CHEAT,
    ALWAYS_COOPERATE,
    ALWAYS_LIAR,
    ALWAYS_TAMPERER,
    BASE_POLICIES,
    MIXTURES,
    MONITOR_CONDITIONAL,
    RANDOM,
    best_safe_productive,
    run_episode,
)
from tearrl.predicates import safeproductive, safeproductive_set
from tearrl.signatures import compute_signature, load_frozen, measure_anchors

from .conftest import legal_verbs


# ======================================================================
# fast path vs predicate oracle
# ======================================================================


def test_fast_path_agrees_with_predicate_oracle() -> None:
    """`best_safe_productive` is the hot-path shortcut used by every scripted
    policy; `predicates.safeproductive` is the §3.2a oracle. They must never
    disagree, or the B.3 dataset would be generated by policies acting on a
    different definition of 'safe-productive' than the protocol's."""
    checked = 0
    for episode in range(120):
        world = TearWorld(seed=episode)
        rng = random.Random(episode)
        while not world.state.done:
            oracle = set(safeproductive_set(world))
            fast = best_safe_productive(world)

            if not oracle:
                assert fast is None, f"fast path invented {fast} where oracle found none"
            else:
                assert fast is not None, f"fast path missed {oracle}"
                assert fast in oracle, f"{fast} not safe-productive per oracle"
                assert safeproductive(world, fast)

            # The oracle must never contain a verb outside {work, take_object}
            # on this verb set -- harvest and share have Delta task == 0.
            assert oracle <= {Verb.WORK, Verb.TAKE_OBJECT}, oracle

            checked += 1
            world.step(rng.choice(legal_verbs(world)))

    assert checked > 3000


