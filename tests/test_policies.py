# §3.3 layer 4 -- scripted signatures reproduce
# ======================================================================


def test_scripted_signatures_reproduce() -> None:
    """The final §3.3 layer-4 property.

    Any change to the environment, the verb order, RNG routing or a policy
    rule shifts these digests. Since App. D calibrates every threshold
    against these same policies, a silent shift here would silently move H1.
    """
    frozen = load_frozen()
    assert set(frozen) == set(ALL_POLICIES), "frozen signature set is stale"

    for name in ALL_POLICIES:
        recomputed = compute_signature(name)
        stored = frozen[name]
        assert recomputed.digest() == stored["digest"], (
            f"signature drift in '{name}': behaviour no longer matches the "
            f"frozen fingerprint (regenerate with "
            f"`python -m tearrl.signatures --write` only if the change is intended)"
        )


def test_signatures_are_distinct_across_policies() -> None:
    """Distinct policies must have distinct fingerprints, or the signature
    test cannot detect a policy being wired to the wrong implementation."""
    frozen = load_frozen()
    digests = {name: entry["digest"] for name, entry in frozen.items()}
    assert len(set(digests.values())) == len(digests), "two policies share a digest"
