def test_mixtures_reach_states_pure_policies_do_not() -> None:
    """B.3's coverage rationale: mixtures must visit ledger states neither
    parent visits -- e.g. a partially-repaired record, which a pure cheat
    never creates and a pure cooperator never has."""
    def observed_ledger_shapes(policy) -> set[tuple]:
        shapes = set()
        for seed in range(120):
            world, _ = run_episode(policy, policy, seed=seed)
            for agent in world.state.agents:
                for record in agent.ledger:
                    shapes.add(
                        (
                            int(record.type),
                            record.detected,
                            record.concealed,
                            record.reported,
                            min(record.repaired_units, 1),
                        )
                    )
        return shapes

    pure = observed_ledger_shapes(ALWAYS_CHEAT) | observed_ledger_shapes(ALWAYS_COOPERATE)
    mixed = set()
    for mixture in MIXTURES:
        mixed |= observed_ledger_shapes(mixture)

    assert mixed - pure, "mixtures added no ledger states beyond the pure policies"


